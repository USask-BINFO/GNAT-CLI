"""
Move GNs based on relative size to query
"""

import argparse
from os import listdir, path, mkdir
from shutil import move

parser = argparse.ArgumentParser("Move GNs based on size compared to query size from parsed psi-BLAST file.")
parser.add_argument("-t", help="% size threshold. Default=0.20", type=float, default=0.20)
parser.add_argument("psi_file", help="Parsed psi-BLAST file generated by parse_psiblast_out.py.")
parser.add_argument("-f", help="Location of files to separate. Default current directory.")
parser.add_argument("-o", help="Directory to separate files into (creates a potentially_spurious/ and non_spurious/)."
                               "Defaults to -f")

args = parser.parse_args()

gn_pid = {}
with open(args.psi_file, "r") as f:
    for line in f:
        l = line.rstrip().split()
        acc = l[1]
        ratio = abs(float(l[7])-1)
        gn_pid[acc] = float(ratio)

file_dir = '.'
if args.f is not None and path.isdir(args.f):
    file_dir = args.f

out_dir = file_dir
if args.o is not None and path.isdir(args.o):
    out_dir = args.o

outside = []
within = []
for file in listdir(file_dir):
    if '.gb' in file[-3:]:
        acc = file.split("_")[-2]
        if gn_pid[acc] < args.t:
            within.append(file)
        else:
            outside.append(file)

within_dir = path.join(out_dir, "in_size")
outside_dir = path.join(out_dir, "out_size")

mkdir(within_dir)
mkdir(outside_dir)

for file in within:
    #rename(path.join(file_dir, file), path.join(spur_dir, file))
    #replace(path.join(file_dir, file), path.join(spur_dir, file))
    move(path.join(file_dir, file), path.join(within_dir, file))

for file in outside:
    #rename(path.join(file_dir, file), path.join(non_spur_dir, file))
    #replace(path.join(file_dir, file), path.join(non_spur_dir, file))
    move(path.join(file_dir, file), path.join(outside_dir, file))

