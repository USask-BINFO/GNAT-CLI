#! /usr/bin/env python3
"""
Move GNs based on a PID threshold compared to query
"""

import argparse
from os import listdir, path, mkdir
from shutil import move

parser = argparse.ArgumentParser("Move GNs based on PID to query from parsed PSI-BLAST file.")
parser.add_argument("-t", help="PID threshold. Default=30", type=float, default=30.)
parser.add_argument("psi_file", help="Parsed PSI-BLAST file generated by parse_psiblast_out.py.")
parser.add_argument("-f", help="Location of files to separate. Default current directory.")
parser.add_argument("-o", help="Directory to separate files into (creates a potentially_homologous/ and homologous/)."
                               "Defaults to -f")

args = parser.parse_args()

gn_pid = {}
with open(args.psi_file, "r") as f:
    for line in f:
        l = line.rstrip().split()
        acc = l[1]
        pid = l[4]
        gn_pid[acc] = float(pid)

file_dir = '.'
if args.f is not None and path.isdir(args.f):
    file_dir = args.f

out_dir = file_dir
if args.o is not None and path.isdir(args.o):
    out_dir = args.o

spur = []
non_spur = []
for file in listdir(file_dir):
    if '.gb' in file[-3:]:
        acc = file.split("_")[-2]

        potential_prefix = file.split("_")[-3]

        # Check if acc is '_' delimited like WP_#########.#
        if acc[:-2].isdigit() and len(potential_prefix) == 2 and potential_prefix.isalpha() and potential_prefix.isupper():
            acc = "_".join([potential_prefix] + [acc])

        if gn_pid[acc] < args.t:
            spur.append(file)
        else:
            non_spur.append(file)

spur_dir = path.join(out_dir, path.abspath(out_dir).split("/")[-1].split(".")[0]+"_below_PID_threshold")
non_spur_dir = path.join(out_dir, path.abspath(out_dir).split("/")[-1].split(".")[0]+"_above_PID_threshold")

if len(spur) > 0:
    mkdir(spur_dir)
    for file in spur:
        move(path.join(file_dir, file), path.join(spur_dir, file))

if len(non_spur_dir) > 0:
    mkdir(non_spur_dir)
    for file in non_spur:
        move(path.join(file_dir, file), path.join(non_spur_dir, file))
