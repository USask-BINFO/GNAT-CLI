#! /usr/bin/env python
"""
Script to update the match labelling file used to label matches in the clinker plots.
Can also be used to change the name of matches in the label file (e.g., rename acc. # to protein name).
"""
import argparse
from sys import stdout
from label_cls import LabelObject
from os import path
from LabelFile import LabelFile

# Parse arguments
parser = argparse.ArgumentParser("Update the label file used for match names in the clinker plots.")

parser.add_argument("label_file", help="Path to the label file to update. This file will be the one that is updated if -p is specified.")
parser.add_argument("-p", "--parsed", help="Path to the parsed psiblast output file containing matches. This should be a file generated by parse_psiblast_out.py.")
# parser.add_argument("-m", "--modify", help="Path to the file containing old labels mapped to the new labels. Each line should consist of two tab delimited items: the old label and the new label.") Deleted for now
# parser.add_argument("-o", "--out", help="Path and name of the output file when -m is specified. If not specified, writes -m modified output to stdout.")
parser.add_argument("-l", "--merge_label_file", help="Merge two label files. The file provided here will be merged with the label file provided in the first argument. The two files must be the same format. The first argument will be updated with the merged labels. The format of the merged file will be the same as the original label file. This file will not have its class labels transferred.")

args = parser.parse_args()

# Create LabelFile object
if not path.exists(args.label_file):
    raise FileNotFoundError(f"Label file {args.label_file} does not exist.")
label_file = LabelFile(args.label_file)

# Verify either parsed or modify file was provided
if not args.parsed and not args.modify and not args.merge_label_file:
    raise ValueError("Either a parsed PSI-BLAST output file or a modify file must be provided.")

# Update label object based on parsed PSI-BLAST output file
if args.parsed:
    if not path.exists(args.parsed):
        raise FileNotFoundError(f"Parsed PSI-BLAST output file {args.parsed} does not exist.")
    
    # Read the parsed PSI-BLAST output file
    with open(args.parsed, "r") as f:
        for line in f:
            # Parsed PSI-BLAST file format: GCA    Accession    E_Value    Label    .... Rest not important
            accession, eval, label = line.split()[1:4]

            # Get the label file delimiter
            delim = label_file.delim if label_file.delim is not None else '\t'
            line = f"{accession}{delim}{label}{delim}{eval}"

            # Add any neccessary empty columns to the end of the line
            line += delim * (len(label_file.header.split(',')) - 3)

            label_file.add_line(line)

if args.merge_label_file:
    if not path.exists(args.merge_label_file):
        raise FileNotFoundError(f"Merge label file {args.merge_label_file} does not exist.")
    
    # Get the number of classes in the original label file
    label_header_len = len(label_file.header.split(','))

    # Read the merge label file
    with open(args.merge_label_file, "r") as f:
        for line in f:
            if len(line.split(',')) < 3:
                if len(line.split()) < 3:
                    raise ValueError(f"Merge label file {args.merge_label_file} does not have valid delimeters.")
                else:
                    delim = None
            else:
                delim = ','

            accession, label, eval = line.split(delim)[:3]

            # Get the label file delimiter
            delim = label_file.delim
            line = f"{accession}{delim}{label}{delim}{eval}" + delim * (label_header_len - 3)
            label_file.add_line(line)

# Write updated label object to output file or stdout
