#! /usr/bin/env python
"""
Script to update the match labelling file used to label matches in the clinker plots.
Can also be used to change the name of matches in the label file (e.g., rename acc. # to protein name).
"""
import argparse
from sys import stdout
from label_cls import LabelObject

# Parse arguments
parser = argparse.ArgumentParser("Update the label file used for match names in the clinker plots.")

parser.add_argument("label_file", help="Path to the label file to update. This file will be the one that is updated if -p is specified.")
parser.add_argument("-p", "--parsed", help="Path to the parsed psiblast output file containing matches. This should be a file generated by parse_psiblast_out.py.")
parser.add_argument("-m", "--modify", help="Path to the file containing old labels mapped to the new labels. Each line should consist of two tab delimited items: the old label and the new label.")
parser.add_argument("-o", "--out", help="Path and name of the output file when -m is specified. If not specified, writes -m modified output to stdout.")
parser.add_argument("-l", "--merge_label_file", help="Merge two label files. The file provided here will be merged with the label file provided in the first argument. The first argument will be updated with the merged labels. The format of the merged file will be the same as the original label file.")

args = parser.parse_args()

# Using label file, create a LabelObject
label_obj = LabelObject()
label_obj.from_file(args.label_file)

# Verify either parsed or modify file was provided
if not args.parsed and not args.modify and not args.merge_label_file:
    raise ValueError("Either a parsed PSI-BLAST output file or a modify file must be provided.")

# Update label object based on parsed PSI-BLAST output file
if args.parsed:
    label_obj.merge_parsed_psi_file(args.parsed)

# Modify label object based on modify file
if args.modify:
    with open(args.modify, "r") as f:
        modify_lines = [line.rstrip().split() for line in f]
    
    for line in modify_lines:
        if len(line) != 2:
            raise ValueError("Each line in the modify file must contain two tab-delimited items: the old label and the new label.")
        else:
            old_label, new_label = line
            label_obj.rename_label(old_label, new_label)

if args.merge_label_file:
    label_obj.merge_label_file(args.merge_label_file)

# Write updated label object to output file or stdout
label_lines = str(label_obj)

if args.modify:
    if args.out:
        with open(args.out, "w") as f:
            f.write(label_lines)
    else:
        stdout.write(label_lines)
else:
    # Parsed PSI-BLAST output file, update provided label file
    with open(args.label_file, "w") as f:
        f.write(label_lines)

