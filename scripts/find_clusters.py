"""
Class to generate GN clusters based on kmer features in GN nucleotide sequences.
"""
import copy
from os import listdir, path, mkdir#, getcwd
from Bio import SeqIO
import numpy
from sklearn.cluster import KMeans
from sklearn.exceptions import ConvergenceWarning
import argparse
from shutil import move
import math

import kmer as kmer
import warnings

import generate_svg

warnings.simplefilter("error", ConvergenceWarning)


class Cluster:
    def __init__(self, gn_dir, k=3):
        """
        Generates distance matrix to be used for k-means clustering
        """
        self.gn_dir = gn_dir
        self.lower = None
        self.upper = None
        self.genomes = {}
        self.indices = {}
        self.matrix = self.sequence_matrix(k)

    def sequence_matrix(self, k):
        """
        Generates a matrix for clustering based on nucleotide k-mers
        """
        self.genomes = {}
        self.indices = {}

        i = 0
        for gn in listdir(self.gn_dir):
            if '.gb' in gn:
               self.genomes[gn] = i
               self.indices[i] = gn
               i += 1

        seq_list = []
        for gn in self.genomes.keys():
            for seq_record in SeqIO.parse(path.join(self.gn_dir, gn), "genbank"):
                seq_list.append(seq_record.seq)

        obj = kmer.kmer_featurization(k)
        kmer_features = obj.obtain_kmer_feature_for_a_list_of_sequences(seq_list, write_number_of_occurrences=False)

        return kmer_features

    def kmeans(self, matrix, k):
        """
        Run k-means on a distance matrix
        :param matrix: Distance matrix generated in __init__, or a sub-matrix generated from it.
        :param k: The number of clusters to generate.
        return: A list of lists of indices. Each sublist is one cluster. Each index is a genome (mapped in indices{})
        """
        if k <= 1:
            k = 2

        try:
            estimator = KMeans(n_clusters=k, algorithm="lloyd", n_init=10) # Used to be algorithm="full" and no n_init, but prev n_init default was 10 so keeping like this
            labels = estimator.fit_predict(matrix)
        except ConvergenceWarning:
            indices = [i for i in range(len(matrix))]

            def sub_split(a, n):
                """Split list a into n parts"""
                l, m = divmod(len(a), n)
                return [a[i * l + min(i, m):(i + 1) * l + min(i + 1, m)] for i in range(n)]

            labels = sub_split(indices, k)
            tmp = []
            for i in range(len(labels)):
                for j in range(len(labels[i])):
                    tmp.append(i)
            labels = tmp

        clust_dict = {}
        res_list = []
        for i in range(len(labels)):
            if labels[i] not in clust_dict.keys():
                clust_dict[labels[i]] = [i]
            else:
                clust_dict[labels[i]].append(i)
        for key in clust_dict.keys():
            res_list.append(clust_dict[key])

        return res_list

    def genbank_to_index(self, gb_name):
        """
        Convert a genbank name to its mapped index
        """
        return self.genomes[gb_name]

    def index_to_genbank(self, index):
        """
        Convert an index to its mapped genbank name
        """
        return self.indices[index]

    def genbank_list_to_index(self, gb_list):
        """
        Convert a list of genbank names to a list of their mapped indices
        """
        tmp = []
        for gb in gb_list:
            tmp.append(self.genomes[gb])
        return tmp

    def index_list_to_genbank(self, index_list):
        """
        Convert a list of indices to a list of their mapped genbank names
        """
        tmp = []
        for i in index_list:
            tmp.append(self.indices[i])
        return tmp

    def evaluate_clusters(self, clusters, min_thresh, max_thresh):
        """
        Check if clusters generated by kmeans() are within a length threshold.
        :param clusters: list of lists returned by kmeans()
        :param min_thresh: Minimum length of clusters
        :param max_thresh: Maximum length of clusters
        return: Three nested lists: small, good, and large. Each list contains lists of indices that are either too
        small (small), too large (large), or within the threshold (good).
        """
        n = len(clusters)
        counter = [0 for i in range(0, n)]
        for i in range(len(clusters)):
            counter[i] = len(clusters[i])

        small = []
        large = []
        good = []

        for i in range(0, n):
            if counter[i] < min_thresh:
                small.append(clusters[i])
            elif counter[i] > max_thresh:
                large.append(clusters[i])
            else:
                good.append(clusters[i])

        return small, good, large

    def sub_matrix(self, cluster_indices):
        """
        Returns a sub matrix based on specified indices (representing clusters)
        """
        keep_indices = []
        all_indices = [i for i in range(len(self.matrix))]
        for index_list in cluster_indices:
            for index in index_list:
                keep_indices.append(index)

        del_indices = all_indices.copy()
        m = copy.deepcopy(self.matrix)

        keep_indices.sort(reverse=True)

        for i in keep_indices:
            del del_indices[i]

        del_indices.reverse()

        for i in del_indices:
            m = numpy.delete(m, i, 0)

        new_to_old = {}
        keep_indices.reverse()
        for i in range(len(keep_indices)):
            new_to_old[i] = keep_indices[i]

        return m, new_to_old

    def break_down_large_clusters(self, small_cluster, good_cluster, large_cluster, desired):
        """
        A function to repeatedly run kmeans() on the too-large clusters that were initially generated until large is
        empty. Used to empty 'large' (list containing too-large clusters generated by evaluate_clusters())
        :param small_cluster: small from evaluate_clusters()
        :param good_cluster: good from evaluate_clusters()
        :param large_cluster: large cluster nested list desired to be removed
        return: No return, modifies param lists
        """
        while len(large_cluster) > 0:
            # Just take first element of large over and over, then append new larges to large
            l = large_cluster[0]
            sub, d = self.sub_matrix([l])
            k = len(sub)//desired
            if k <= 1:
                k = 2
            sub_cluster = self.kmeans(sub, k)

            for index_list in sub_cluster:
                for i in range(len(index_list)):
                    index_list[i] = d[index_list[i]] # Convert index numbers to old index numbers

            sub_small, sub_good, sub_large = self.evaluate_clusters(sub_cluster, self.lower, self.upper)

            for g in sub_good:
                good_cluster.append(g)
            for s in sub_small:
                small_cluster.append(s)
            for l in sub_large:
                large_cluster.append(l)

            del large_cluster[0]

    def clump_small_clusters(self, small_cluster, good_cluster, large_cluster, min_thresh, max_thresh):
        """
        Clumps the too-small clusters together, and moves them to another list based on their new size. Used to empty
        'small' (list containing too-small clusters generated by evaluate_clusters())
        :param small_cluster: small from evaluate_clusters()
        :param good_cluster: good from evaluate_clusters()
        :param large_cluster: large from evaluate_clusters()
        :param min_thresh: same as from evaluate_clusters()
        :param max_thresh: same as from evaluate_clusters()
        return: Nothing, changes contents of cluster list params
        """
        new_small = []
        for cluster in small_cluster:
            for index in cluster:
                new_small.append(index)

        if len(new_small) <= 0:
            pass    # Just to make sure nothing bad happens if small_cluster is empty

        elif len(new_small) < min_thresh:   # All small clusters are smaller than the minimum desired length
            low = None
            for g in range(len(good_cluster)):
                if low is None:
                    low = g
                elif len(good_cluster[low]) > len(good_cluster[g]):
                    low = g

            if len(good_cluster[low]) + len(new_small) > max_thresh:
                # Put lowest good with new_small in large
                for i in good_cluster[low]:
                    new_small.append(i)
                del good_cluster[low]
                large_cluster.append(new_small)

            else:
                # Just add to good (within threshold)
                for i in new_small:
                    good_cluster[low].append(i)

        elif len(new_small) > max_thresh:
            large_cluster.append(new_small)

        else:
            good_cluster.append(new_small)  # new_small within threshold

        while len(small_cluster) > 0:
            del small_cluster[0]    # Empty small cluster as its contents have been moved

    def sized_clusters(self, min_thresh, max_thresh, desired_size=None):
        """
        Generate clusters within a size threshold, used to generate clusters for plotting.
        :param min_thresh: Lower bound (inclusive) for desired cluster size.
        :param max_thresh: Upper bound (inclusive) for desired cluster size.
        :param desired_size: Optional: desired number of GNs in cluster. If not specified, takes midpoint of specified
                             range.
        return: Best clusters within the range specified. (list of lists)
        """
        self.lower = min_thresh
        self.upper = max_thresh

        if desired_size:
            n = desired_size
        else:
            n = (min_thresh+max_thresh)/2
        num_clusters = len(self.matrix)//n
        if num_clusters <= 1:
            num_clusters = 2
        #print(num_clusters)
        clusters = self.kmeans(self.matrix, num_clusters)

        small, good, large = self.evaluate_clusters(clusters, min_thresh, max_thresh)

        while not (len(large) == 0) or not (len(small) == 0):
            self.break_down_large_clusters(small, good, large, n)
            self.clump_small_clusters(small, good, large, min_thresh, max_thresh)

        return good

    def to_string(self, clusters):
        """
        Returns a string version of the input clusters
        :param clusters: List of list of indices returned by sized_clusters() or best_clusters()
        return: A string parse-able by cluster_directories.sh
        """
        ret_str = ""

        # Translate indices in clusters to genome names
        counter = 0
        for cluster in clusters:
            ret_str += "-----Next Cluster-----\n"
            name = path.basename(self.gn_dir).split(".")[0]
            ret_str += name + "_cluster_" + str(counter) + "\n"
            counter += 1
            for i in range(len(cluster)):
                cluster[i] = self.indices[cluster[i]]
                ret_str += cluster[i] + "\n"

        return ret_str


def main():
    """
    Main function to generate clusters and move the GNs into their separate directories.
    """
    parser = argparse.ArgumentParser("Generate kmer-based clusters of GNs.")
    parser.add_argument("gn_dir", help="Directory containing genomic neighbourhoods to be clustered.")
    parser.add_argument("out_name", help="Name of clusters ('out_name'_cluster_#).")
    parser.add_argument("-o", "--out_dir", help="Name of directory to send clusters to. Defaults to gn_dir.")
    parser.add_argument("-k", type=int, help="Size of kmers (default=3). Increasing this will drastically increase "
                                             "runtime.", default=3)
    parser.add_argument("-s", "--cluster_size", type=int, default=10, help="Desired number of GNs per cluster. "
                                                                           "(default 10)")
    parser.add_argument("--min_thresh", type=int, default=5, help="Lowest number of GNs per cluster (default 5).")
    parser.add_argument("--max_thresh", type=int, default=15, help="Highest number of GNs per cluster (default 15).")
    parser.add_argument("--max_genes", type=int, default=41, help="Maximum number of genes that can be in a GN (default 41). This doesn't affect the generation of GNs, it just tells the program how genes to expect in each.")

    args = parser.parse_args()

    if args.min_thresh > args.cluster_size or args.min_thresh > args.max_thresh:
        raise ValueError("[--min_thresh] (%i) must be lower than [-s][--cluster_size] (%i) and [--max_thresh] "
                         "(%i)." % (args.min_thresh, args.cluster_size, args.max_thresh))
    if args.max_thresh < args.cluster_size or args.max_thresh < args.min_thresh:
        raise ValueError("[--max_thresh] (%i) must be higher than [-s][--cluster_size] (%i) and [--min_thresh] "
                         "(%i)." % (args.max_thresh, args.cluster_size, args.min_thresh))

    if args.max_thresh <= 0 or args.min_thresh <= 0 or args.cluster_size <= 0:
        raise ValueError("[--max_thresh] (%i), [--min_thresh] (%i), and [-s][--cluster_size] (%i) must be positive.")
    
    rawdir = listdir(args.gn_dir)
    gns_only = []
    for item in rawdir:
        if ".gb" in item:
            gns_only.append(item)

    if len(gns_only) < 1:
        exit()
    elif len(gns_only) <= args.min_thresh:
        clusters = []
        c = None
        clusters.append(gns_only)
    else:
        # Generate clusters
        c = Cluster(args.gn_dir, k=args.k)
        clusters = c.sized_clusters(min_thresh=args.min_thresh, max_thresh=args.max_thresh, desired_size=args.cluster_size)

    # Calculate a score and the 'average' GN for each cluster to determine the ordering of the cluster directories
    cluster_scores = []

    # Initialize dict to store the 'average' GN and addtl data for each cluster
    # Key is cluster stored in cluster_scores, value is:
        # {'avg_orientations': [1, 1, 1, -1, -1, 1, 0, 1, 1, -1, -1, 1, -1], 'num_GNs': int}
        # Where the sign is the orientation of the gene (0 is the match, always forward strand +)
    average_representations = {}

    for cluster in clusters:
        score = 0 # init cluster score
        all_orientations = []

        if c is not None:
            names = c.index_list_to_genbank(cluster)
        else:
            names = cluster
        
        for gn in names:
            # This is used to help calculate the 'average' orientations
            orientations = {'before': [], 'match': [], 'after': []}
            current_block = []
            query_block_flag = -1 # < 0 before match block, 0 at match block, > 0 after match block
            
            # Numbers for scoring
            num_genes = 0
            num_query_block = 0
            num_orientation_blocks = 0

            # Slice name of match off of gb filename
            query_match_name = gn.split("_")[-2]
            gn_score = 0 # init GN score
            with open(path.join(args.gn_dir, gn), "r") as gn_file:
                for record in SeqIO.parse(gn_file, "genbank"):
                    # Extract the orientation blocks (and update scoring numbers)
                    for feature in record.features:
                        if feature.type == "CDS":
                            num_genes += 1

                            # Handle first gene
                            if len(current_block) == 0:
                                current_block.append(feature)
                            
                            # Handle genes in same block
                            elif feature.strand == current_block[-1].strand:
                                current_block.append(feature)
                            
                            # Handle block flip (current strand != prev strand)
                            else:
                                # Figure out if the new block contains the query match
                                for f in range(len(current_block)):
                                    feat = current_block[f]
                                    if "protein_id" in feat.qualifiers and query_match_name in feat.qualifiers['protein_id']:
                                        query_block_flag = 0
                                        orientations['match_idx'] = f
                                    
                                if query_block_flag < 0:
                                    orientations['before'].append(current_block)

                                elif query_block_flag == 0:
                                    orientations['match'].append(current_block)
                                    orientations['match_strand'] = current_block[0].strand
                                    query_block_flag += 1

                                else:
                                    orientations['after'].append(current_block)

                                # Wipe current_block
                                current_block = [feature]

                    # Ensure last block also gets added
                    for f in range(len(current_block)):
                        feat = current_block[f]
                        if "protein_id" in feat.qualifiers and query_match_name in feat.qualifiers['protein_id']:
                            query_block_flag = 0
                            orientations['match_idx'] = f
                        
                    if query_block_flag < 0:
                        orientations['before'].append(current_block)

                    elif query_block_flag == 0:
                        orientations['match'].append(current_block)
                        orientations['match_strand'] = current_block[0].strand
                        query_block_flag += 1

                    else:
                        orientations['after'].append(current_block)

                    num_orientation_blocks = len(orientations['before']) + len(orientations['match']) + len(orientations['after'])

            gn_score = 5 * (num_genes/args.max_genes) # Favour closer to max num genes in each GN (high weight)
            gn_score += 2 * (num_query_block/num_genes) # Favour more genes in the same naive synteny block as query match (moderate weight)
            gn_score += 1 * max(0, (num_genes/num_orientation_blocks) - 4)/max((num_genes-4),1) # Favour synteny blocks larger than 4 genes on avg (low weight)
            gn_score = gn_score / 8 # Ensure values are [0,1] by dividing by sum of weights
            score += gn_score

            orientations["name"] = gn

            all_orientations.append(orientations)
        
        score = score/len(names) # Normalize GN scores by dividing by number of GNs
        score *= 2     # Weighting the GN portion of the score
        
        # Calculate another term to reward GN clusters having closest to args.cluster_size (default 20) GNs, falling off to 0
        half_dist = (args.cluster_size - args.min_thresh)/2
        gaussian_score = math.exp(-((len(names) - args.cluster_size)**2))/(half_dist**2)

        score += gaussian_score
        score /= 3 # Normalize [0,1]

        cluster_scores.append((cluster, score))

        for i in range(len(all_orientations)):
            # Change the representation of the orientation blocks
            before = all_orientations[i]["before"]
            match = all_orientations[i]["match"]
            after = all_orientations[i]["after"]
            
            match = [1 for _ in range(len(match[0]))]
            match[all_orientations[i]["match_idx"]] = 0

            multiplier = -1
            new_before = []
            for j in range(len(before)-1,-1,-1):
                new_before = [1 * multiplier for _ in range(len(before[j]))] + new_before
                multiplier *= -1
            before = new_before

            multiplier = -1
            new_after = []
            for j in range(len(after)):
                new_after += [1 * multiplier for _ in range(len(after[j]))]
                multiplier *= -1
            after = new_after

            if all_orientations[i]["match_strand"] == -1:
                # If match is on the negative strand, flip the orientations
                before, after, match = after[::-1], before[::-1], match[::-1]

            all_orientations[i]["before"] = before
            all_orientations[i]["match"] = match
            all_orientations[i]["after"] = after
            all_orientations[i]["full"] = before + match + after
        
        # Use the representations in all_orientations to calculate the 'average' GN for the cluster
        # Align the representations on the match gene
        frequency_position_list = [{} for _ in range(args.max_genes)]
        for i in range(len(all_orientations)):
            # Pad the representations with None to ensure they are all the same length, 
            # ensure at least (max_genes - 1)/2 on each side of match
            before = all_orientations[i]["before"].copy()
            match = all_orientations[i]["match"].copy()
            after = all_orientations[i]["after"].copy()

            pivot_flag = False
            for j in range(len(match)):
                orientation = match[j]
                if orientation == 0:
                    pivot_flag = True
                    continue

                if not pivot_flag:
                    before.append(orientation)
                else:
                    after = [orientation] + after
            
            # Ensure before and after have exactly n elements
            # Pads with None if less than n
            # Truncates furthest element if greater than n
            #   Only ever exceeds n if the edge gene has another gene overlapping it (e.g. some viral genomes)
            flanking_n = (args.max_genes - 1)/2
            while len(before) != flanking_n:
                if len(before) < flanking_n:
                    before = [None] + before
                elif len(before) > flanking_n:
                    before = before[1:]
            
            while len(after) != flanking_n:
                if len(after) < flanking_n:
                    after = after + [None]
                elif len(after) > flanking_n:
                    after = after[:-1]
            
            # Concatenation of the max-sized flanks plus the match
            full = before + [0] + after

            all_orientations[i]["padded"] = full

            # Get the frequencies of the orientation at each possible position in the GNs to calculate the averages
            for j in range(len(full)):
                orientation = full[j]
                if orientation is not None:
                    if j not in frequency_position_list:
                        frequency_position_list[j] = {}
                        # try:
                        #     frequency_position_list[j] = {}
                        # except IndexError:
                        #     print(f"j: {j}")
                        #     print(f"len(frequency_position_list): {len(frequency_position_list)}")
                        #     print(f"len(full): {len(full)}")
                        #     print(f"frequency_position_list: {frequency_position_list}")
                        #     print(f"full: {full}")
                        #     print(f"all_orientations[i]: {all_orientations[i]}")
                        #     frequency_position_list[j] = {}
                        #     exit()
                    if orientation not in frequency_position_list[j]:
                        frequency_position_list[j][orientation] = 1
                    else:
                        frequency_position_list[j][orientation] += 1
                else:
                    if "None" not in frequency_position_list[j]:
                        frequency_position_list[j]["None"] = 1
                    else:
                        frequency_position_list[j]["None"] += 1
        
        # Get the most common orientations from frequency_position_list
        max_orientations = []
        for freqs in frequency_position_list:
            max_orientation = None
            max_freq = 0
            for orientation in freqs.keys():
                if freqs[orientation] > max_freq:
                    max_orientation = orientation
                    max_freq = freqs[orientation]
                elif freqs[orientation] == max_freq:
                    # Placeholder to handle edge case where there's a tie
                    pass
            max_orientations.append(max_orientation)

        # # Testing        
        # for i in range(len(all_orientations)):
        #     print(all_orientations[i]["padded"])
        # print(max_orientations)
        # exit()

        average_representations[str(score)] = {'avg_orientations': max_orientations, 'num_GNs': len(names), 'cluster': cluster}


    # Sort the clusters based on scores
    cluster_scores = sorted(cluster_scores, key=lambda x: x[1], reverse=True)

    # Make cluster directories and move GNs into their respective cluster directories
    #print("Current dir: %s" % getcwd())
    dir_header = args.out_name
    if args.out_dir:
        outdir = args.out_dir
    else:
        outdir = args.gn_dir
    counter = 0

    for cluster, score in cluster_scores:
        counter += 1
        if c is not None:
            names = c.index_list_to_genbank(cluster)
        else:
            names = cluster
        cluster_dir = path.join(outdir, dir_header+"_cluster_"+str(counter))
        mkdir(cluster_dir)

        for gn in names:
            # Move GN
            move(path.join(args.gn_dir, gn), path.join(cluster_dir, gn))
        
        # Output score
        with open(path.join(cluster_dir, ".score.txt"), "w") as score_file:
            score_file.write(str(score))

        # Output average GN
        average_gn = average_representations[str(score)]['avg_orientations']
        generate_svg.create_svg_from_orientation(average_gn, path.join(cluster_dir, ".representation.svg"))


main()

