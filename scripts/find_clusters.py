#! /usr/bin/env python3
"""
Class to generate GN clusters based on kmer features in GN nucleotide sequences.
"""
import copy
from os import listdir, path, mkdir#, getcwd
from Bio import SeqIO
import numpy
from sklearn.cluster import KMeans
from sklearn.exceptions import ConvergenceWarning
import argparse
from shutil import move

import kmer
import warnings

warnings.simplefilter("error", ConvergenceWarning)


class Cluster:
    def __init__(self, gn_dir, k=3):
        """
        Generates distance matrix to be used for k-means clustering
        """
        self.gn_dir = gn_dir
        self.lower = None
        self.upper = None
        self.genomes = {}
        self.indices = {}
        self.matrix = self.sequence_matrix(k)

    def sequence_matrix(self, k):
        """
        Generates a matrix for clustering based on nucleotide k-mers
        """
        self.genomes = {}
        self.indices = {}

        i = 0
        for gn in listdir(self.gn_dir):
            if '.gb' in gn:
               self.genomes[gn] = i
               self.indices[i] = gn
               i += 1

        seq_list = []
        for gn in self.genomes.keys():
            for seq_record in SeqIO.parse(path.join(self.gn_dir, gn), "genbank"):
                seq_list.append(seq_record.seq)

        obj = kmer.kmer_featurization(k)
        kmer_features = obj.obtain_kmer_feature_for_a_list_of_sequences(seq_list, write_number_of_occurrences=False)

        return kmer_features

    def kmeans(self, matrix, k):
        """
        Run k-means on a distance matrix
        :param matrix: Distance matrix generated in __init__, or a sub-matrix generated from it.
        :param k: The number of clusters to generate.
        return: A list of lists of indices. Each sublist is one cluster. Each index is a genome (mapped in indices{})
        """
        if k <= 1:
            k = 2

        try:
            estimator = KMeans(n_clusters=k, algorithm="full")
            labels = estimator.fit_predict(matrix)
        except ConvergenceWarning:
            indices = [i for i in range(len(matrix))]

            def sub_split(a, n):
                """Split list a into n parts"""
                l, m = divmod(len(a), n)
                return [a[i * l + min(i, m):(i + 1) * l + min(i + 1, m)] for i in range(n)]

            labels = sub_split(indices, k)
            tmp = []
            for i in range(len(labels)):
                for j in range(len(labels[i])):
                    tmp.append(i)
            labels = tmp

        clust_dict = {}
        res_list = []
        for i in range(len(labels)):
            if labels[i] not in clust_dict.keys():
                clust_dict[labels[i]] = [i]
            else:
                clust_dict[labels[i]].append(i)
        for key in clust_dict.keys():
            res_list.append(clust_dict[key])

        return res_list

    def genbank_to_index(self, gb_name):
        """
        Convert a genbank name to its mapped index
        """
        return self.genomes[gb_name]

    def index_to_genbank(self, index):
        """
        Convert an index to its mapped genbank name
        """
        return self.indices[index]

    def genbank_list_to_index(self, gb_list):
        """
        Convert a list of genbank names to a list of their mapped indices
        """
        tmp = []
        for gb in gb_list:
            tmp.append(self.genomes[gb])
        return tmp

    def index_list_to_genbank(self, index_list):
        """
        Convert a list of indices to a list of their mapped genbank names
        """
        tmp = []
        for i in index_list:
            tmp.append(self.indices[i])
        return tmp

    def evaluate_clusters(self, clusters, min_thresh, max_thresh):
        """
        Check if clusters generated by kmeans() are within a length threshold.
        :param clusters: list of lists returned by kmeans()
        :param min_thresh: Minimum length of clusters
        :param max_thresh: Maximum length of clusters
        return: Three nested lists: small, good, and large. Each list contains lists of indices that are either too
        small (small), too large (large), or within the threshold (good).
        """
        n = len(clusters)
        counter = [0 for i in range(0, n)]
        for i in range(len(clusters)):
            counter[i] = len(clusters[i])

        small = []
        large = []
        good = []

        for i in range(0, n):
            if counter[i] < min_thresh:
                small.append(clusters[i])
            elif counter[i] > max_thresh:
                large.append(clusters[i])
            else:
                good.append(clusters[i])

        return small, good, large

    def sub_matrix(self, cluster_indices):
        """
        Returns a sub matrix based on specified indices (representing clusters)
        """
        keep_indices = []
        all_indices = [i for i in range(len(self.matrix))]
        for index_list in cluster_indices:
            for index in index_list:
                keep_indices.append(index)

        del_indices = all_indices.copy()
        m = copy.deepcopy(self.matrix)

        keep_indices.sort(reverse=True)

        for i in keep_indices:
            del del_indices[i]

        del_indices.reverse()

        for i in del_indices:
            m = numpy.delete(m, i, 0)

        new_to_old = {}
        keep_indices.reverse()
        for i in range(len(keep_indices)):
            new_to_old[i] = keep_indices[i]

        return m, new_to_old

    def break_down_large_clusters(self, small_cluster, good_cluster, large_cluster, desired):
        """
        A function to repeatedly run kmeans() on the too-large clusters that were initially generated until large is
        empty. Used to empty 'large' (list containing too-large clusters generated by evaluate_clusters())
        :param small_cluster: small from evaluate_clusters()
        :param good_cluster: good from evaluate_clusters()
        :param large_cluster: large cluster nested list desired to be removed
        return: No return, modifies param lists
        """
        while len(large_cluster) > 0:
            # Just take first element of large over and over, then append new larges to large
            l = large_cluster[0]
            sub, d = self.sub_matrix([l])
            k = len(sub)//desired
            if k <= 1:
                k = 2
            sub_cluster = self.kmeans(sub, k)

            for index_list in sub_cluster:
                for i in range(len(index_list)):
                    index_list[i] = d[index_list[i]] # Convert index numbers to old index numbers

            sub_small, sub_good, sub_large = self.evaluate_clusters(sub_cluster, self.lower, self.upper)

            for g in sub_good:
                good_cluster.append(g)
            for s in sub_small:
                small_cluster.append(s)
            for l in sub_large:
                large_cluster.append(l)

            del large_cluster[0]

    def clump_small_clusters(self, small_cluster, good_cluster, large_cluster, min_thresh, max_thresh):
        """
        Clumps the too-small clusters together, and moves them to another list based on their new size. Used to empty
        'small' (list containing too-small clusters generated by evaluate_clusters())
        :param small_cluster: small from evaluate_clusters()
        :param good_cluster: good from evaluate_clusters()
        :param large_cluster: large from evaluate_clusters()
        :param min_thresh: same as from evaluate_clusters()
        :param max_thresh: same as from evaluate_clusters()
        return: Nothing, changes contents of cluster list params
        """
        new_small = []
        for cluster in small_cluster:
            for index in cluster:
                new_small.append(index)

        if len(new_small) <= 0:
            pass    # Just to make sure nothing bad happens if small_cluster is empty

        elif len(new_small) < min_thresh:   # All small clusters are smaller than the minimum desired length
            low = None
            for g in range(len(good_cluster)):
                if low is None:
                    low = g
                elif len(good_cluster[low]) > len(good_cluster[g]):
                    low = g

            if len(good_cluster[low]) + len(new_small) > max_thresh:
                # Put lowest good with new_small in large
                for i in good_cluster[low]:
                    new_small.append(i)
                del good_cluster[low]
                large_cluster.append(new_small)

            else:
                # Just add to good (within threshold)
                for i in new_small:
                    good_cluster[low].append(i)

        elif len(new_small) > max_thresh:
            large_cluster.append(new_small)

        else:
            good_cluster.append(new_small)  # new_small within threshold

        while len(small_cluster) > 0:
            del small_cluster[0]    # Empty small cluster as its contents have been moved

    def sized_clusters(self, min_thresh, max_thresh, desired_size=None):
        """
        Generate clusters within a size threshold, used to generate clusters for plotting.
        :param min_thresh: Lower bound (inclusive) for desired cluster size.
        :param max_thresh: Upper bound (inclusive) for desired cluster size.
        :param desired_size: Optional: desired number of GNs in cluster. If not specified, takes midpoint of specified
                             range.
        return: Best clusters within the range specified. (list of lists)
        """
        self.lower = min_thresh
        self.upper = max_thresh

        if desired_size:
            n = desired_size
        else:
            n = (min_thresh+max_thresh)/2
        num_clusters = len(self.matrix)//n
        if num_clusters <= 1:
            num_clusters = 2
        #print(num_clusters)
        clusters = self.kmeans(self.matrix, num_clusters)

        small, good, large = self.evaluate_clusters(clusters, min_thresh, max_thresh)

        while not (len(large) == 0) or not (len(small) == 0):
            self.break_down_large_clusters(small, good, large, n)
            self.clump_small_clusters(small, good, large, min_thresh, max_thresh)

        return good

    def to_string(self, clusters):
        """
        Returns a string version of the input clusters
        :param clusters: List of list of indices returned by sized_clusters() or best_clusters()
        return: A string parse-able by cluster_directories.sh
        """
        ret_str = ""

        # Translate indices in clusters to genome names
        counter = 0
        for cluster in clusters:
            ret_str += "-----Next Cluster-----\n"
            name = path.basename(self.gn_dir).split(".")[0]
            ret_str += name + "_cluster_" + str(counter) + "\n"
            counter += 1
            for i in range(len(cluster)):
                cluster[i] = self.indices[cluster[i]]
                ret_str += cluster[i] + "\n"

        return ret_str


def main():
    """
    Main function to generate clusters and move the GNs into their separate directories.
    """
    parser = argparse.ArgumentParser("Generate kmer-based clusters of GNs.")
    parser.add_argument("gn_dir", help="Directory containing genomic neighbourhoods to be clustered.")
    parser.add_argument("out_name", help="Name of clusters ('out_name'_cluster_#).")
    parser.add_argument("-o", "--out_dir", help="Name of directory to send clusters to. Defaults to gn_dir.")
    parser.add_argument("-k", type=int, help="Size of kmers (default=3). Increasing this will drastically increase "
                                             "runtime.", default=3)
    parser.add_argument("-s", "--cluster_size", type=int, default=20, help="Desired number of GNs per cluster. "
                                                                           "(default 20)")
    parser.add_argument("--min_thresh", type=int, default=10, help="Lowest number of GNs per cluster (default 10).")
    parser.add_argument("--max_thresh", type=int, default=30, help="Highest number of GNs per cluster (default 30).")

    args = parser.parse_args()

    if args.min_thresh > args.cluster_size or args.min_thresh > args.max_thresh:
        raise ValueError("[--min_thresh] (%i) must be lower than [-s][--cluster_size] (%i) and [--max_thresh] "
                         "(%i)." % (args.min_thresh, args.cluster_size, args.max_thresh))
    if args.max_thresh < args.cluster_size or args.max_thresh < args.min_thresh:
        raise ValueError("[--max_thresh] (%i) must be higher than [-s][--cluster_size] (%i) and [--min_thresh] "
                         "(%i)." % (args.max_thresh, args.cluster_size, args.min_thresh))

    if args.max_thresh <= 0 or args.min_thresh <= 0 or args.cluster_size <= 0:
        raise ValueError("[--max_thresh] (%i), [--min_thresh] (%i), and [-s][--cluster_size] (%i) must be positive.")
    
    rawdir = listdir(args.gn_dir)
    gns_only = []
    for item in rawdir:
        if ".gb" in item:
            gns_only.append(item)

    if len(gns_only) < 1:
        exit()
    elif len(gns_only) <= args.min_thresh:
        clusters = []
        c = None
        clusters.append(gns_only)
    else:
        # Generate clusters
        c = Cluster(args.gn_dir, k=args.k)
        clusters = c.sized_clusters(min_thresh=args.min_thresh, max_thresh=args.max_thresh, desired_size=args.cluster_size)

    # Make cluster directories and move GNs into their respective cluster directories
    #print("Current dir: %s" % getcwd())
    dir_header = args.out_name
    if args.out_dir:
        outdir = args.out_dir
    else:
        outdir = args.gn_dir
    counter = 0
    for cluster in clusters:
        counter += 1
        if c is not None:
            names = c.index_list_to_genbank(cluster)
        else:
            names = cluster
        cluster_dir = path.join(outdir, dir_header+"_cluster_"+str(counter))
        mkdir(cluster_dir)
        for gn in names:
            move(path.join(args.gn_dir, gn), path.join(cluster_dir, gn))


main()

