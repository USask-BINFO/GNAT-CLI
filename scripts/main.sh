#! /usr/bin/env bash

# Run main.sh -h for help

# Before running, add directory containing gnat scripts to path
# Also add scripts/clinker to path

# Necessary arguments:
# query_file; database

# Optional arguments:
# label_file_location; PID_threshold; length_threshold; num_flanking_genes; evalue; num_iterations; scripts

# Parse command-line arguments
# Make sure some arguments were provided
if [[ $# -lt 1 ]]; then
  echo "No arguments provided, call main.sh -h or main.sh --help for help."
  exit 1
fi

# Assign default values to arguments in case they aren't provided
evalue=0.01
num_iter=4
num_flanking_genes=15
pid_threshold=30
length_threshold=20
out_location=$(pwd)
out_tag=$(date +%j%M%H%S)
tax_flag=false

# Parse arguments
while [[ $# -gt 0 ]]; do
  case $1 in
    -q|--query_file)
      query_file="$2"
      shift
      shift
      ;;
    -p|--psiblast_out_file)
      psiblast_out_file="$2"
      shift
      shift
      ;;
    -d|--database)
      database="$2"
      shift
      shift
      ;;
    -h|--help)
      echo "      Main script to generate phylogenetic trees and pie charts, genomic neighbourhoods, and clinker plots of"
      echo "      PSI-BLAST matches to the specified query/queries."
      echo "Required Arguments:"
      echo '  [-d][--database]                Path to root directory of database generated by db_scripts/get_ncbi_genomes.'
      echo '                                    The last directory in the path should end with "_db", e.g., '
      echo '                                    /path/to/bacterial_db/'
      echo '  [-q][--query_file]              Path to file containing protein query(ies). Either this argument OR '
      echo '                                    [-p][--psiblast_out_file] are required.'
      echo '  [-p][--psiblast_out_file]       Path to file generated by run_psiblasts.sh. This will skip the long PSI-BLAST'
      echo '                                    step of the pipeline. Either this argument OR [-q] [--query_file] are required.'
      echo '                                    Format of PSI-BLAST out should be as follows: '
      echo '                                      qname qacc sacc pident qlen slen evalue'
      echo '                                    This file should match *.out (as the ones generated by run_psiblasts.sh do).'
      echo "Potentially Required Arguments:"
      echo '  [-s][--scripts]                 Directory containing GNAT pipeline scripts, if they were not added to PATH. If not'
      echo '                                    provided, assumes that scripts have been added to PATH.'
      echo "Optional Arguments:"
      echo '  [-e][--evalue]                  E-value for psi-BLAST search. Default=0.01'
      echo '  [-h][--help]                    Prints this message.'
      echo '  [-i][--num_iter]                Number of psi-BLAST iterations. Default=4'
      echo '  [-l][--length_threshold]        Percentage length threshold for match filtering. Filters out match genomic neighbourhoods'
      echo '                                    that are outside of +-length_threshold/100*query_length. Default=20'
      echo '  [-lf][--label_file_location]    Location of label match file containing query names, protein match accessions,'
      echo '                                   and e-values of the matches. Generated/updated by parse_psiblast_out.py. If'
      echo '                                   not specified, creates a new label file in out folder.'
      echo '  [-n][--num_flanking_genes]      Number of genes to include upstream/downstream of match gene. Default=15'
      echo '  [-ol][--out_location]           Location to create output directory in. Defaults to the current directory'
      echo '  [-ot][--out_tag]                Descriptor in output directory name. Defaults to a string of 9 numbers. The '
      echo '                                    first three are the current day (001-365), and the next six are HHMMSS.'
      echo '  [-pid][--pid_threshold]         PID threshold for match filtering. Filters out match genomic neighbourhoods'
      echo '                                    that are less than pid_threshold identical. The default value is intended'
      echo '                                    to filter matches as homologous or potentially homologous. Default=30'
      echo '  [-tf][--tax_flag]               Only use this flag if the database being queried is the ncbi bacterial '
      echo '                                    database. If specified, will try to generate phylogenetic trees and pie '
      echo '                                    charts, which may crash the program if any other dataset is used. Outputs '
      echo '                                    a csv file containing the taxonomic data of matches in both cases.'
      exit 0
      ;;
    -e|--evalue)
      evalue="$2"
      shift
      shift
      ;;
    -i|--num_iter)
      num_iter="$2"
      shift
      shift
      ;;
    -n|--num_flanking_genes)
      num_flanking_genes="$2"
      shift
      shift
      ;;
    -lf|--label_file_location)
      label_file_location="$2"
      shift
      shift
      ;;
    -pid|--pid_threshold)
      pid_threshold="$2"
      shift
      shift
      ;;
    -l|--length_threshold)
      length_threshold="$2"
      shift
      shift
      ;;
    -s|--scripts)
      script_dir="$2"
      shift
      shift
      ;;
    -ol|--out_location)
      out_location="$2"
      shift
      shift
      ;;
    -tf|--tax_flag)
      tax_flag=true
      shift
      ;;
    -ot|--out_tag)
      out_tag="$2"
      shift
      shift
      ;;
    "")
      shift
      ;;
    -*)
      echo "Unknown option $1"
      exit 1
      ;;
    *)
      echo "Argument not associated with a flag: $1"
      exit 1
      ;;
  esac
done

curr_dir=$(pwd)
# Check that required arguments were provided
if [ -z ${query_file+x} ]; then
  if [ -z ${psiblast_out_file+x} ]; then
    echo "Error: Must specify either [-q][--query_file] or [-p][--psiblast_out_file]."
    exit 1
  fi
else
  if [ ! -z ${psiblast_out_file+x} ]; then
    echo "Error: Only one of [-q][--query_file] and [-p][--psiblast_out_file] may be specified."
    exit 1
  fi
fi
if [ -z ${database+x} ]; then
  echo "Required argument [-d][--database] not specified."
  exit 1
fi

# Check if scripts were specified, if not, assume in PATH
if [ -z ${script_dir+x} ]; then
  echo "[-s][--scripts] not specified. Assuming scripts have been added to PATH."
  script_dir=""
else
  script_dir=$(cd "$script_dir" || exit; pwd; cd "$curr_dir" || exit;)
  script_dir="$script_dir/"
fi

# Make sure paths are absolute, find necessary database directories
echo "Checking paths..."
database_root=$(cd "$database"/ || exit; pwd; cd "$curr_dir" || exit)
org_name_db=$(basename "$database")
org_name="${org_name_db%_db}"

database=$(cd "$database_root"/"$org_name"db || exit; pwd; cd "$curr_dir" || exit)
echo "BlastDB found!"
gbff=$(cd "$database_root"/"$org_name"_genomes/gbff || exit; pwd; cd "$curr_dir" || exit)
echo "GBFFs found!"
out_location=$(cd "$out_location" || exit; pwd; cd "$curr_dir" || exit)

outdir="$out_location"/gnat_out_"$out_tag"

# Check if outdir exists, if so, exit
if [ -d "$outdir" ]; then
  echo "Error: directory $outdir exists. Specify a different -ot or -ol. Exiting...";
  exit 1;
fi

# Create the output directory
mkdir "$outdir"


# Create log file
logfile="$outdir"/log.txt
touch "$logfile"

echo "Starting..."
echo "Starting..." > "$logfile"

# Get the start time in ms
start_time=$(date +%s%3N)
echo "Start: $start_time" >> "$logfile"

# Run scripts
cd "$outdir" || exit 1

# Check if a query file was provided, if so, run PSI-BLASTs
if [ ! -z ${query_file+x} ]; then
  # Get the absolute path to the query_file
  working_dir=$(pwd)
  cd "$curr_dir" || exit 1
  cd "$(dirname "$query_file")" || exit 1
  query_file="$(pwd)"/"$(basename "$query_file")"
  cd "$working_dir" || exit 1

  echo "Query file: $(basename $query_file)"
  echo "Query file: $(basename $query_file)" >> "$logfile"
  echo "Running PSI-BLASTs"
  echo "Running PSI-BLASTs" >> "$logfile"
  "${script_dir}"run_psiblasts.sh "$database" "$query_file" "$evalue" "$num_iter"

  psi_blast_finish_time=$(date +%s%3N)

  echo "PSI-BLASTs finished: $psi_blast_finish_time" >> "$logfile"
  echo "PSI-BLASTs finished: $psi_blast_finish_time"
  echo "Time to run PSI-BLASTs: $((psi_blast_finish_time - start_time)) ms" >> "$logfile"
  echo "Time to run PSI-BLASTs: $((psi_blast_finish_time - start_time)) ms"

  query_filename=$(basename "$query_file")
  psiblast_out_file="$outdir"/"${query_filename%.fasta}".out
else
  if [ ! -z $psiblast_out_file ]; then
    # Get the absolute path to the PSI-BLAST output file if one was provided instead of a query
    working_dir=$(pwd)
    cd "$curr_dir" || exit 1
    cd "$(dirname "$psiblast_out_file")" || exit 1
    psiblast_out_file="$(pwd)"/"$(basename "$psiblast_out_file")"
    cd "$working_dir" || exit 1
  fi
fi

# Create and assign label_file_location if not specified
if [ -z ${label_file_location+x} ];
then
  # Make sure no label file already exists
  if [ -f "$out_tag".label ]; then
    echo "$out_tag.label already exists in output directory. Please specify a different label file location. Exiting..." >> "$logfile"
    echo "$out_tag.label already exists in output directory. Please specify a different label file location. Exiting..."
    exit 1
  else
    echo "No label file specified, creating new $out_tag.label in output directory." >> "$logfile"
    echo "No label file specified, creating new $out_tag.label in output directory."
    touch "$out_tag".label
    label_file_location="$PWD/$out_tag.label"
  fi
fi

label_file_name=$(basename "$label_file_location")
echo "Using $label_file_name as match gene labelling file." >> "$logfile"
echo "Using $label_file_name as match gene labelling file."

# Get relevant info from psiblast output (GBFF_NAME MATCH_ACCESSION QUERY_ACCESSION E_VALUE PID QUERY_LEN MATCH_LEN MATCH_LEN/QUERY_LEN)
# Also updates the label file with new match data
echo "Parsing PSI-BLAST output..." >> "$logfile"
echo "Parsing PSI-BLAST output..."
"${script_dir}"parse_psiblast_out.py "$psiblast_out_file"

# For each .parsed file in the current directory, run modify_label_file.py to update the label file with new match data
num_matches=0
parsed_directories=()

for file in *.parsed
do
  file_matches=$(cat "$file" | wc -l)
  (( num_matches += file_matches ))

  "${script_dir}"modify_label_file.py "$label_file_location" -p "$file"

  # Create a subdirectory for each parsed output file if it had matches
  if [[ "$file_matches" -gt 0 ]]; then
    filename=$(basename "$file")
    mkdir "${filename%.parsed}"
    mv "$file" "${filename%.parsed}"/

    # Generate genomic neighbourhoods for each file containing matches
    echo "Creating GNs for $file" >> "$logfile"
    echo "Creating GNs for $file"
    "${script_dir}"build_gn.py "${filename%.parsed}"/"$file" -d "$gbff" -o "${filename%.parsed}"/ -n "$num_flanking_genes"

    parsed_directories=("${parsed_directories[@]}" "${filename%.parsed}")
  fi
done

# Check if there are any matches after filtering, if not, exit.
if [[ $num_matches -eq 0 ]]; then
  echo "No non-redundant PSI-BLAST matches to any query. Exiting..." >> "$logfile"
  echo "No non-redundant PSI-BLAST matches to any query. Exiting..."
  exit 0
fi

# Filter GNs based on size, PID, redundancy, kmer. Generate phylo data for each filtering step
for dir in "${parsed_directories[@]}";
do
  # Generate phylo data for all of the GNs generated
  "${script_dir}"generate_krona_plot.py "$psiblast_out_file" -o "$dir"/all.krona.html

  echo "Filtering GNs for $dir and generating phylogeny data." >> "$logfile"
  echo "Filtering GNs for $dir and generating phylogeny data."

  # Remove redundants based on aa-seq
  "${script_dir}"redundancy.py "$dir"

  # Get names of .gb files left in current directory
  gb_files=("$dir"/*.gb)

  # Generate phylo data for all the non-redundant GNs
  "${script_dir}"generate_krona_plot.py "$psiblast_out_file" "$gb_files" -o "$dir"/all_non_redundants.krona.html

  # Copy all GNs into new non-redundants directory
  mkdir "$dir"/all_non_redundants
  cp "$dir"/*.gb "$dir"/all_non_redundants

  # Run clustering on NR directory
  "${script_dir}"find_clusters.py "$dir"/all_non_redundants "$(basename "$dir" | cut -f1 -d ".")_non_redundant" --max_genes $((2*$num_flanking_genes+1))

  # Run plotting on NR clusters
  echo "Generating phylogeny data and clinker plots for all non-redundant clusters in $dir" >> "$logfile"
  echo "Generating phylogeny data and clinker plots for all non-redundant clusters in $dir"

  if [[ $(ls "$dir"/all_non_redundants | wc -l) -gt 0 ]]; then
      for cluster_dir in "$dir"/all_non_redundants/*_cluster_*
        do
          # Generate phylo data and clinker plots for each cluster in all_non_redundants
          gb_files=("$cluster_dir"/*.gb)

          "${script_dir}"generate_krona_plot.py "$psiblast_out_file" "$gb_files" -o "$cluster_dir"/all_non_redundants.krona.html

          "${script_dir}"run_clinker_main.sh "$cluster_dir"/*.gb -p "$cluster_dir"/"$(basename "$cluster_dir")".html -lf "$label_file_location"

          mkdir "$cluster_dir"/genbank_files
          mv "$cluster_dir"/*.gb "$cluster_dir"/genbank_files
        done
  fi

  # Split GNs into two directories based on PID (threshold = 30%)
  "${script_dir}"pid_filter.py "$dir"/"$dir".parsed -f "$dir" -t "$pid_threshold"

  for h in "$dir"/*PID*
  do
    # Generate Krona plots for both PID filtered directories
    gb_files=("$h"/*.gb)

    "${script_dir}"generate_krona_plot.py "$psiblast_out_file" "$gb_files" -o "$h"/$(basename "$h").krona.html

    # Split GNs into two directories based on size (within/outside 20% (default) query protein length)
    "${script_dir}"size_filter.py "$dir"/"$dir".parsed -f "$h" -t "$length_threshold"

    for s in "$h"/*size
    do
      # Generate Krona plots for both size filtered directories
      gb_files=("$s"/*.gb)

      "${script_dir}"generate_krona_plot.py "$psiblast_out_file" "$gb_files" -o "$s"/$(basename "$s").krona.html

      # Generate kmer clusters (second argument is for first part of cluster dir name)
      "${script_dir}"find_clusters.py "$s" "$(basename "$s")" --max_genes $((2*$num_flanking_genes+1))

      # If there are clusters, generate Krona and Clinker plots for each cluster
      if [[ $(ls "$s" | wc -l) -gt 0 ]]; then
      echo "Generating Krona and Clinker plots for all clusters in $s" >> "$logfile"
      echo "Generating Krona and Clinker plots for all clusters in $s"

      for cluster_dir in "$s"/*_cluster_*
        do
          # Generate Krona and Clinker plots for each cluster
          gb_files=("$cluster_dir"/*.gb)

          "${script_dir}"generate_krona_plot.py "$psiblast_out_file" "$gb_files" -o "$cluster_dir"/krona.html

          "${script_dir}"run_clinker_main.sh "$cluster_dir"/*.gb -p "$cluster_dir"/"$(basename "$cluster_dir")".html -lf "$label_file_location"

          mkdir "$cluster_dir"/genbank_files
          mv "$cluster_dir"/*.gb "$cluster_dir"/genbank_files
        done
      fi
    done
  done
done

echo "Output to $outdir" >> "$logfile"
echo "Output to $outdir"


