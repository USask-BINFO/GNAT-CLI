#! /usr/bin/env bash

# Run main.sh -h for help

# Before running, add directory containing acr_aca_vis scripts to path
# Also add scripts/clinker to path

# Necessary arguments:
# query_directory; database

# Optional arguments:
# label_file_location; PID_threshold; length_threshold; num_flanking_genes; evalue; num_iterations; scripts

# Parse command-line arguments
# Make sure some arguments were provided
if [[ $# -lt 1 ]]; then
  echo "No arguments provided, call main.sh -h or main.sh --help for help."
  exit 1
fi

# Assign default values to arguments in case they aren't provided
evalue=0.01
num_iter=4
num_flanking_genes=20
pid_threshold=30
length_threshold=0.20
out_location=$(pwd)
out_tag=$(date +%j%M%H%S)
tax_flag="o"

# Parse arguments
while [[ $# -gt 0 ]]; do
  case $1 in
    -q|--query_directory)
      query_directory="$2"
      shift
      shift
      ;;
    -p|--psiblast_out_directory)
      psiblast_out_directory="$2"
      shift
      shift
      ;;
    -d|--database)
      database="$2"
      shift
      shift
      ;;
    -g|--gbff)
      gbff="$2"
      shift
      shift
      ;;
    -h|--help)
      echo "      Main script to generate phylogenetic trees and pie charts, genomic neighbourhoods, and clinker plots of"
      echo "      psi-BLAST matches to the specified query/queries."
      echo "Required Arguments:"
      echo '  [-d][--database]                Path to database to query against.'
      echo '  [-g][--gbff]                    GBFF directory.'
      echo '  [-q][--query_directory]         Path to directory containing protein fasta queries. Either this argument OR '
      echo '                                    [-p][--psiblast_out_directory] are required.'
      echo '  [-p][--psiblast_out_directory]  Path to directory containing files generated by run_psiblasts.sh. This will '
      echo '                                    skip the long psi-BLAST step of the pipeline. Either this argument OR [-q] '
      echo '                                    [--query] are required. Format of psiBLAST out should be as follows: '
      echo '                                      qacc sacc pident qcovhsp length mismatch gapopen qstart qend sstart send '
      echo '                                      qlen slen evalue'
      echo '                                    Psi-BLAST out files should match *.all.out (as the ones generated by '
      echo '                                    run_psiblasts.sh do).'
      echo "Potentially Required Arguments:"
      echo '  [-s][--scripts]                 Directory containing acrvis scripts, if they were not added to PATH. If not'
      echo '                                    provided, assumes that scripts have been added to PATH.'
      echo "Optional Arguments:"
      echo '  [-e][--evalue]                  E-value for psi-BLAST search. Default=0.01'
      echo '  [-h][--help]                    Prints this message.'
      echo '  [-i][--num_iter]                Number of psi-BLAST iterations. Default=4'
      echo '  [-l][--length_threshold]        Length threshold for match filtering. Filters out match genomic neighbourhoods'
      echo '                                    that are outside of +-length_threshold*query_length. Default=0.20'
      echo '  [-lf][--label_file_location]    Location of label match file containing query names, protein match accessions,'
      echo '                                   and e-values of the matches. Generated/updated by parse_psiblast_out.py. If'
      echo '                                   not specified, creates a new all_match_names.txt in acrvis folder.'
      echo '  [-n][--num_flanking_genes]      Number of genes to include upstream/downstream of match gene. Default=20'
      echo '  [-ol][--out_location]           Location to create output directory in. Defaults to the current directory'
      echo '  [-ot][--out_tag]                Descriptor in output directory name. Defaults to a string of 9 numbers. The '
      echo '                                    first three are the current day (001-365), and the next six are HHMMSS.'
      echo '  [-pid][--pid_threshold]         PID threshold for match filtering. Filters out match genomic neighbourhoods'
      echo '                                    as "potentially homologous" that are less than pid_threshold identical.'
      echo '                                    Default=30'
      echo '  [-tf][--tax_flag]               Only use this flag if the database being queried is the ncbi bacterial '
      echo '                                    database. If specified, will try to generate phylogenetic trees and pie '
      echo '                                    charts, which may crash the program if any other dataset is used. Outputs '
      echo '                                    a csv file containing the taxonomic data of matches in both cases.'
      exit 0
      ;;
    -e|--evalue)
      evalue="$2"
      shift
      shift
      ;;
    -i|--num_iter)
      num_iter="$2"
      shift
      shift
      ;;
    -n|--num_flanking_genes)
      num_flanking_genes="$2"
      shift
      shift
      ;;
    -lf|--label_file_location)
      label_file_location="$2"
      shift
      shift
      ;;
    -pid|--pid_threshold)
      pid_threshold="$2"
      shift
      shift
      ;;
    -l|--length_threshold)
      length_threshold="$2"
      shift
      shift
      ;;
    -s|--scripts)
      script_dir="$2"
      shift
      shift
      ;;
    -ol|--out_location)
      out_location="$2"
      shift
      shift
      ;;
    -tf|--tax_flag)
      tax_flag="b"
      shift
      ;;
    -ot|--out_tag)
      out_tag="$2"
      shift
      shift
      ;;
    -*)
      echo "Unknown option $1"
      exit 1
      ;;
    *)
      echo "Argument not associated with a flag: $1"
      exit 1
      ;;
  esac
done

# Check that required arguments were provided
if [ -z ${query_directory+x} ]; then
  if [ -z ${psiblast_out_directory+x} ]; then
    echo "Error: Must specify either [-q][--query_directory] or [-p][--psiblast_out_directory]."
    exit 1
  fi
else
  if [ ! -z ${psiblast_out_directory+x} ]; then
    echo "Error: Only one of [-q][--query_directory] and [-p][--psiblast_out_directory] may be specified."
  fi
fi
if [ -z ${database+x} ]; then
  echo "Required argument [-d][--database] not specified."
  exit 1
fi
if [ -z ${gbff+x} ]; then
  echo "Required argument [-g][--gbff] not specified."
  exit 1
fi

# Check if scripts were specified, if not, assume in PATH
curr_dir=$(pwd)
if [ -z ${script_dir+x} ]; then
  echo "[-s][--scripts] not specified. Assuming scripts have been added to PATH."
  script_dir=""
else
  script_dir=$(cd "$script_dir" || exit; pwd; cd "$curr_dir" || exit;)
  script_dir="$script_dir/"
fi

# Make sure paths are absolute
database=$(cd "$database" || exit; pwd; cd "$curr_dir" || exit)
query_directory=$(cd "$query_directory" || exit; pwd; cd "$curr_dir" || exit)
gbff=$(cd "$gbff" || exit; pwd; cd "$curr_dir" || exit)
out_location=$(cd "$out_location" || exit; pwd; cd "$curr_dir" || exit)

echo "Starting..."

# Run scripts
outdir="$out_location"/acrvis_out_"$out_tag"
if [ -d "$outdir" ]; then
  echo "Error: directory $outdir exists. Specify a different -ot or -ol. Exiting...";
  exit 1;
fi
mkdir "$outdir"
cd "$outdir" || exit 1
mkdir psiblast_out
mkdir parsed_outs
cd psiblast_out || exit 1

if [ -z ${query_directory+x} ]; then
  # Run Psi-BLASTs
  echo "Running Psi-BLASTs"
  "${script_dir}"run_psiblasts.sh "$database" "$query_directory" "$evalue" "$num_iter"
else
  echo "Using Psi-BLAST outputs from $psiblast_out_directory"
  cp "$psiblast_out_directory/*.all.out" "."
fi
cd ..

# Create and assign label_file_location if not specified
if [ -z ${label_file_location+x} ];
then
  touch all_match_names.txt
  label_file_location="$PWD/all_match_names.txt"
fi

echo "Using $label_file_location as match gene labelling file."

# Get relevant info from psiblast output (PID, qsize, ssize, qname, gbffname)
# Also updates the label file with new match data
for file in "$PWD"/psiblast_out/*.all.out
do
  "${script_dir}"parse_psiblast_out.py "$file" -m "$label_file_location" > parsed_outs/"$(basename "$file")".parsed
done


mkdir data
# Create a subdirectory for each query
for query in parsed_outs/*.parsed
do
  v=$(cat "$query" | wc -l)
  if [[ "$v" -gt 0 ]]; then
    mkdir data/"$(basename "$query")";
  fi
done

for file in parsed_outs/*.parsed
do
  "${script_dir}"build_gn.py "$file" -d "$gbff" -o "data/$(basename "$file")/" -n "$num_flanking_genes"
done

# Filter GNs based on size, PID, redundancy, kmer. Generate phylo data for each filtering step
for dir in data/*
do
  # TODO: rewrite phylo script
  # TODO Raw Phylo Data
  "${script_dir}"generate_phylogeny_data.py "$dir" -n $(basename "$dir" | cut -f1 -d '.')_raw -dt $(echo "$gbff" | rev | cut -f2 -d '/' | rev | cut -f1 -d '_') -o "$dir"

  # Remove redundants based on aa-seq
  "${script_dir}"redundancy.py "$dir"
  # TODO Non-Redundant Phylo Data
  "${script_dir}"generate_phylogeny_data.py "$dir" -n $(basename "$dir" | cut -f1 -d '.')_non_redundant -dt $(echo "$gbff" | rev | cut -f2 -d '/' | rev | cut -f1 -d '_') -o "$dir"

  # Copy all GNs into new non-redundants directory
  mkdir "$dir"/all_non_redundants
  cp "$dir"/*.gb "$dir"/all_non_redundants
  # Run clustering on NR directory
  "${script_dir}"find_clusters.py "$dir"/all_non_redundants "$(basename "$dir" | cut -f1 -d ".")_non_redundant"
  # Run plotting on NR clusters
  if [[ $(ls "$dir"/all_non_redundants | wc -l) -gt 0 ]]; then
      for cluster_dir in "$dir"/all_non_redundants/*_cluster_*
        do
        # TODO Cluster Phylo Data
          "${script_dir}"generate_phylogeny_data.py "$cluster_dir" -n $(basename "$cluster_dir") -dt $(echo "$gbff" | rev | cut -f2 -d '/' | rev | cut -f1 -d '_') -o "$cluster_dir"
          "${script_dir}"run_clinker_main.sh "$cluster_dir"/*.gb -p "$cluster_dir"/"$(basename "$cluster_dir")".html -lf "$label_file_location"
        done
  fi

  # Split GNs into two directories based on PID (threshold = 30%)
  "${script_dir}"pid_filter.py parsed_outs/"$(basename "$dir")" -f "$dir" -t "$pid_threshold"
  for h in "$dir"/*homologous
  do
    # TODO PID Phylo Data
    "${script_dir}"generate_phylogeny_data.py "$h" -n $(basename "$h") -dt $(echo "$gbff" | rev | cut -f2 -d '/' | rev | cut -f1 -d '_') -o "$h" 
    # Split GNs into two directories based on size (within/outside 20% (default) query protein length)
    "${script_dir}"size_filter.py parsed_outs/"$(basename "$dir")" -f "$h" -t "$length_threshold"
    for s in "$h"/*size
    do
      # TODO Size Phylo Data
      "${script_dir}"generate_phylogeny_data.py "$s" -n $(basename "$s") -dt $(echo "$gbff" | rev | cut -f2 -d '/' | rev | cut -f1 -d '_') -o "$s"
      # Generate kmer clusters (second argument is for first part of cluster dir name)
      "${script_dir}"find_clusters.py "$s" "$(basename "$s")"
      if [[ $(ls "$s" | wc -l) -gt 0 ]]; then
      for cluster_dir in "$s"/*_cluster_*
        do
          # TODO Cluster Phylo Data
          "${script_dir}"generate_phylogeny_data.py "$cluster_dir" -n $(basename "$cluster_dir") -dt $(echo "$gbff" | rev | cut -f2 -d '/' | rev | cut -f1 -d '_') -o "$cluster_dir"
          "${script_dir}"run_clinker_main.sh "$cluster_dir"/*.gb -p "$cluster_dir"/"$(basename "$cluster_dir")".html -lf "$label_file_location"
        done
      fi
    done
  done
done

echo "Output to $outdir"


