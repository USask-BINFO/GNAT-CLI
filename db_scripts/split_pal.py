#! /usr/bin/env python
"""
Program used to split a .pal file generated by makeblastdb into several smaller pals that can be psiBLASTed against.
Creates a file called all_pal_files.txt listing the names of the split pals to be used for psiblasting

Run as "cat dbname.pal | split_pal.py" in the database directory (creates all_pal_files.txt in current directory)
"""

from sys import stdin

# Input: cat dbname.pal | split_pal.py
# Pal File Format (ignore first '# ' on each line):
# #
# # Alias file created: Month DD, YYYY HH:MM am/pm
# #
# TITLE dbpalname
# DBLIST dbname.00 dbname.01 dbname.02 ......

line_list = []
for line in stdin:
    line_list.append(line.rstrip())

# First three lines of pal file are the same (see above) => default_start
# In other words: only the last two lines of the file change/matter for the purposes of this script.
default_start = ''
for i in range(len(line_list)):
    if i < 3:
        default_start += line_list[i] + '\n'


volume_section = {}
counter = 0

# Get all the volumes (dbname.##) from the 5th line of the pal file; ' ' delimited, ignore first item (DBLIST)
temp_list = []
for volume in line_list[4].split(" ")[1:]:
    temp_list.append(volume)
    num = int(volume.split('.')[-1])
    # Split volumes into sets of 250 TODO: change to specifiable number in the future
    if num == 0:
        pass
    elif num % 250 == 0:
        volume_section[counter] = temp_list
        temp_list = []
        counter += 1
    elif volume == line_list[4].split(" ")[-1]:
        volume_section[counter] = temp_list

# Build the new split .pal files
title_list = []

for key in volume_section.keys():
    title = line_list[3].split(' ')[1].split('/')[-1] + "_" + str(key)
    title_list.append(title)
    data = default_start
    data += 'TITLE ' + title + '\n'
    data += 'DBLIST'
    for item in volume_section[key]:
        data += ' ' + item
    data += '\n'
    with open(title + ".pal", "w") as f:
        f.write(data)

# Write the names of all the new .pal files to ./all_pal_names.txt
titles = ""
for title in title_list:
    titles += title + '\n'

with open("all_pal_names.txt", "w") as f:
    f.write(titles)

