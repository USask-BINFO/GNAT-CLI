#! /usr/bin/env python

# Script to generate Krona plot given a protein multi-fasta file from a database generated
# by AcrVis.
# The protein file is in {db_name}_db/{db_name}_genomes/proteins/all_{db_name}_proteins.FASTA
# Generates a Krona plot of all the accessions in the database protein fasta file.

# Uses ImportBLAST.pl from KronaTools to generate the Krona plot. Thus, takes the accessions from
# the protein file and converts them to a fake BLAST output file that ImportBLAST.pl can read.

import argparse
import os.path as path
from random import randint
import subprocess
import os
from tqdm import tqdm

parser = argparse.ArgumentParser("Generate Krona plot given PSI-BLAST output generated by the GNAT pipeline and (optionally) the accessions of the match genes to be plotted.")
parser.add_argument("protein_file", help="Path to the protein multi-fasta file from the database generated by AcrVis.")
parser.add_argument("-o", "--output", help="Name and location of file to output. Defaults to ./blast.krona", default="./blast.krona")

args = parser.parse_args()

if path.exists(args.protein_file):
    with open(args.protein_file, "r") as f:
        # Since we have to iterate over the lines here anyway, might
        # as well modify the lines to put them in the format Krona expects
        #
        # Format:
        # [0] Unique match accession (e.g., RMK91773.1) 
        # [1] Match line with additional pipe (e.g., ./GCA_003698635.1_ASM369863v1_genomic.gbff.gz||MCMZ01000023|RMK91773.1|?|57767|57970|hypothetical)
        # [2-5] Doesn't matter as long as they're tab-separated
        # [6-9] Add additional tab-separated items
        # [10] evalue

        with tqdm(desc="Reading protein file", unit="entries") as pbar:
            lines = []

            for line in f:
                line = line.strip()
                if line[0] != ">":
                    continue
                else:
                    accession = line[1:].split("|")[2]
                    lines.append([accession, line[1:], ".", ".", ".", ".", ".", ".", ".", ".", "."])
                    pbar.update()

else:
    print(f"Error: provided file '{args.psiblast_outfile}' not found. Please verify the path is correct.")
    exit()

# Save filtered in a temp file
if args.output == "./blast.krona":
    outdir = path.curdir
else:
    if path.isdir(args.output):
        outdir = args.output
    else:
        outdir = path.dirname(args.output)

temp_name = path.join(outdir, "tmp_krona")
while path.exists(f"{temp_name}.txt"):
    temp_name += str(randint(0, 99))

temp_name += ".txt"

print("Writing to temp file...")
with open(temp_name, "w") as f:
    with tqdm(desc="Writing to temp file", unit="lines", total=len(lines)) as pbar:
        for line in lines:
            f.write("\t".join(line) + "\n")
            pbar.update()

# Parse output location before running Krona
def iterate_filename(filename):
    """
    Adds an iterative integer to the end of a filename (before the extension) to prevent overwrites.
    :param filename: Str filename (and path) to check if it exists & iterate name if it does
    Return: new filename/location
    """
    if not path.exists(filename):
        return filename

    extension = filename.split('.')[-1]
    filename = '.'.join(filename.split('.')[0:-1])
    i = 0
    while path.exists(f"{filename}_{str(i)}.{extension}"):
        i += 1
    filename = f"{filename}_{str(i)}.{extension}"

    print(f"Warning: Provided output file already exists. Writing to '{filename}' instead.")

    return filename

if path.isdir(args.output):
    # Provided a directory to write to, just use default name
    output = path.join(args.output, "blast.krona")
else:
    output = args.output
output = iterate_filename(output)


# Get path to ImportBLAST.pl
db_genus_script_path = path.abspath(__file__)
script_dir = path.join(path.pardir(path.pardir(path.dirname(db_genus_script_path))), "scripts")

krona_path = os.path.join(script_dir, "Krona", "KronaTools", "scripts")
importblastpl_path = os.path.join(krona_path, "ImportBLAST.pl")

print("Generating Krona plot...")
# Run Krona on the temp file
subprocess.run([importblastpl_path, 
               temp_name,
               "-o", output], stdout=subprocess.DEVNULL)

# Remove the temp file
os.remove(temp_name)
