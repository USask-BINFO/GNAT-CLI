#!/usr/bin/env python3
"""
Script to extract the fasta entries for each genus from the main bacterial fasta file using the genera_gbff_dict from extract_phylo_stats.py
"""

import os
import argparse
from tqdm import tqdm
from Bio import SeqIO
import sys

def sizeof_fmt(ds, suffix="B"):
    """
    Helper to keep track of the size of data structures
    param ds: data structure to get the size of
    """
    num = sys.getsizeof(ds)
    for unit in ["", "K", "M", "G", "T", "P", "E", "Z"]:
        if abs(num) < 1024.0:
            return f"{num:3.1f}{unit}{suffix}"
        num /= 1024.0
    return f"{num:.1f}Y{suffix}"

def genus_genomes_txt_to_dict(genus_genomes_txt, gbff_genera_dict={}):
    """
    Adds the gbff files listed in the {genus}_genomes.txt file to the gbff_genera_dict (or a new dict if not provided). Keys are gbff filenames and values are the genera. By the end will be over a million entries.
    param genus_genomes_txt: path to the {genus}_genomes.txt file generated by extract_phylo_stats.py
    param gbff_genera_dict: dictionary where keys are gbff filenames and values are the genera. If not provided, will create a new dictionary
    return: the gbff_genera_dict with the added entries
    """
    genus = os.path.basename(genus_genomes_txt).split("_")[0]
    with open(genus_genomes_txt, "r") as f:
        lines = f.readlines()
        for line in lines:
            gbff = line.strip()
            gbff_genera_dict[gbff] = genus

    return gbff_genera_dict

def extract_genera_fasta(gbff_genera_dict, main_fasta_file, genera, out_dir, num_prots=None):
    """
    For each genus in the gbff genera dict, extract the fasta entries from the main fasta file and write them to a new genus fasta file (all_{genus}_proteins.fasta) in the out_dir. 
    param gbff_genera_dict: dict returned by genus_genomes_txt_to_dict()
    param main_fasta_file: path to the main fasta file containing all bacterial proteins
    param genera: list of genera
    param out_dir: path to the directory to write the genus fasta files to
    param num_prots: total number of proteins in the main fasta file, optional. Just helps estimate how much time is left.
    return: N/A, writes the genus fasta files to out_dir
    """
    if not os.path.exists(out_dir):
        print(f"Output directory {out_dir} does not exist. Creating it.")
        os.makedirs(out_dir)
    
    file_handles = {}
    try:
        # Open all the genus fasta files to skip some overhead opening and closing them in the loop
        for genus in genera:
            file_handles[genus] = open(os.path.join(out_dir, f"all_{genus}_proteins.fasta"), "w")

        # Loop through the main fasta file and write the proteins to the appropriate genus fasta file
        with open(main_fasta_file, "r") as f:
            with tqdm(desc="Extracting fasta entries", unit="entries", total=num_prots) as pbar:
                for record in SeqIO.parse(f, "fasta"):
                    gbff_name = record.id.split("/")[1].split("|")[0]

                    genus = gbff_genera_dict.get(gbff_name, None)

                    if genus is not None:
                        file_handles[genus].write(f">{record.id}\n{record.seq}\n")

                    pbar.update()
    finally:
        # Close all the genus fasta files
        for handle in file_handles.values():
            handle.close()
    

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Build fasta files for each genus database in the specified folder from the specified main fasta file using the gbffs extracted in extract_phylo_stats.py.")
    parser.add_argument("genera_dbs_root", help="Path to the directory containing the genera database subdirectories")
    parser.add_argument("main_fasta_file", help="Path to the main fasta file containing all bacterial proteins")
    parser.add_argument("-t", "--total_proteins_in_fasta", help="Total number of proteins in the main fasta file, optional. Just helps estimate how much time is left.", type=int, default=None)

    args = parser.parse_args()
    genera_dbs_root = args.genera_dbs_root
    main_fasta_file = args.main_fasta_file

    num_prots = args.total_proteins_in_fasta

    out_dir = genera_dbs_root

    genera = []

    gbff_genera_dict = {}
    with tqdm(desc="Reading genera gbff summaries into dict.", unit="genera", total=len(os.listdir(genera_dbs_root))) as pbar:
        for subdir in os.listdir(genera_dbs_root):
            genus = subdir.split("_")[0]
            genus_genomes_txt = os.path.join(genera_dbs_root, subdir, f"{genus}_genomes.txt")
            gbff_genera_dict = genus_genomes_txt_to_dict(genus_genomes_txt, gbff_genera_dict)

            genera.append(genus)

            pbar.update()

    print(f"gbff_genera_dict size: {sizeof_fmt(gbff_genera_dict)}")

    extract_genera_fasta(gbff_genera_dict, main_fasta_file, genera, out_dir, num_prots)

    # Move the new fasta files in the genera_dbs_root to the appropriate genus subdirectory
    for genus in genera:
        os.rename(os.path.join(out_dir, f"all_{genus}_proteins.fasta"), os.path.join(genera_dbs_root, f"{genus}_db", f"all_{genus}_proteins.fasta"))
